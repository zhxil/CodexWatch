using CodexWatch;
using CodexQuotaTray;
var now=new DateTimeOffset(2026,10,16,12,0,0,TimeSpan.Zero);
var settings=new Settings { QuietHours=false };
QuotaSnapshot Snapshot(int used=85,int reset=120,int age=0)=>new(){WeeklyUsedPercent=used,WeeklyResetAt=now.AddMinutes(reset),FetchedAt=now.AddMinutes(-age)};
var count=0;
void Check(string label,bool condition){if(!condition)throw new Exception(label); Console.WriteLine("PASS "+label); count++;}
Alert[] Eval(QuotaSnapshot s)=>AlertPolicy.Evaluate(s,settings,now).ToArray();
Check("healthy quota silent",Eval(Snapshot(40)).Length==0);
Check("warning threshold inclusive",Eval(Snapshot(80)).Single().Key.EndsWith(":warning"));
Check("critical threshold inclusive",Eval(Snapshot(90)).Single().Key.EndsWith(":critical"));
var warning=Eval(Snapshot()).Single(); settings.Delivered[warning.Key]=now;
Check("repeat warning suppressed",Eval(Snapshot()).Length==0);
var critical=Eval(Snapshot(95)).Single(); settings.Delivered[critical.Key]=now;
Check("critical escalates once",critical.Key.EndsWith(":critical") && Eval(Snapshot(95)).Length==0);
Check("recovery does not repeat lower warning",Eval(Snapshot()).Length==0);
Check("reset timestamp jitter does not duplicate",Eval(Snapshot(reset:121)).Length==0);
Check("new quota cycle alerts again",Eval(Snapshot(reset:240)).Length==1);
settings.Delivered.Clear();
Check("reset reminder at boundary",Eval(Snapshot(40,15)).Single().Key.EndsWith(":reset"));
var reset=Eval(Snapshot(40,15)).Single(); settings.Delivered[reset.Key]=now;
Check("repeat reset suppressed",Eval(Snapshot(40,15)).Length==0);
Check("expired quota ignored",Eval(Snapshot(95,0)).Length==0);
Check("stale quota ignored",Eval(Snapshot(95,15,30)).Length==0);
Check("unknown reset ignored",Eval(new(){WeeklyUsedPercent=95,FetchedAt=now}).Length==0);
settings.Alerts=false; Check("notifications disabled",Eval(Snapshot(95)).Length==0); settings.Alerts=true;
settings.QuietHours=true;
var night=new DateTimeOffset(2026,10,16,23,30,0,TimeZoneInfo.Local.GetUtcOffset(now));
Check("quiet hours suppress notification",!AlertPolicy.Evaluate(new(){WeeklyUsedPercent=95,WeeklyResetAt=night.AddHours(2),FetchedAt=night},settings,night).Any());
settings.QuietHours=false;
var both=new QuotaSnapshot{WeeklyUsedPercent=95,WeeklyResetAt=now.AddHours(2),ShortUsedPercent=85,ShortResetAt=now.AddHours(1),FetchedAt=now};
Check("independent quota buckets",Eval(both).Length==2);
var json=System.Text.Json.JsonSerializer.Serialize(settings); var loaded=System.Text.Json.JsonSerializer.Deserialize<Settings>(json)!;
Check("dedup survives serialization",loaded.Delivered.ContainsKey(reset.Key));
var resetSummary="""
{"rateLimits":{"planType":"prolite","primary":{"usedPercent":18,"windowDurationMins":10080,"resetsAt":1792649592}},"rateLimitResetCredits":{"availableCount":3,"credits":[{"status":"available","resetType":"codexRateLimits","expiresAt":1792701643}]}}
""";
using var doc=System.Text.Json.JsonDocument.Parse(resetSummary);
var parsed=CodexAppServerClient.ParseSnapshot(doc.RootElement);
Check("reset count comes from authoritative summary, not detail list length",parsed.AvailableResetCount==3);
Check("reset credit expiry parsed separately from quota reset",parsed.NextResetCreditExpiry?.ToUnixTimeSeconds()==1792701643 && parsed.WeeklyResetAt?.ToUnixTimeSeconds()==1792649592);
using var empty=System.Text.Json.JsonDocument.Parse("{\"rateLimits\":{}}");
Check("missing reset count remains unknown",CodexAppServerClient.ParseSnapshot(empty.RootElement).AvailableResetCount is null);
using var zero=System.Text.Json.JsonDocument.Parse("{\"rateLimits\":{},\"rateLimitResetCredits\":{\"availableCount\":0}}");
Check("zero resets distinguished from unknown",CodexAppServerClient.ParseSnapshot(zero.RootElement).AvailableResetCount==0);
var expirySnapshot=new QuotaSnapshot{FetchedAt=now,AvailableResetCount=3,NextResetCreditExpiry=now.AddHours(4)};
var expiryAlert=Eval(expirySnapshot).Single();
Check("manual reset credit expiry reminder",expiryAlert.Key.StartsWith("手动重置机会:"));
settings.Delivered[expiryAlert.Key]=now;
Check("manual reset expiry reminder deduplicated",Eval(expirySnapshot).Length==0);
Check("no expiry warning for zero usable resets",Eval(new(){FetchedAt=now,AvailableResetCount=0,NextResetCreditExpiry=now.AddHours(4)}).Length==0);
Console.WriteLine($"{count} checks passed");
